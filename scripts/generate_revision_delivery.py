"""Generate manuscript result text, release counts and response locations."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from diagnostic_suite import __version__


def pytest_count(log: str) -> int:
    values = re.findall(r"(?:^|\s)(\d+) passed(?:\s|,|$)", log)
    if not values or re.search(r"\d+ (?:failed|error)", log):
        raise ValueError("A complete passing pytest summary is required")
    return int(values[-1])


def compiled_locations(aux: str) -> dict[str, str]:
    aux = aux.replace(r"\nobreakspace  {}", " ")
    result = {}
    for key, number, page in re.findall(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}\{([^}]*)\}", aux):
        if key.startswith("sec:"):
            label = "Section~" + number
        elif key.startswith("tab:"):
            label = "Table~" + number
        elif key.startswith("fig:"):
            label = "Figure~" + number
        elif key.startswith("app:"):
            label = "Appendix~" + re.sub(r"^Appendix\s*", "", number)
        else:
            continue
        result[key] = label + " (p.~" + page + ")"
    return result


def validated_installation(path: Path, count: int) -> dict:
    result = json.loads((path / "validation.json").read_text())
    if not result["passed"] or not result["resume_preserved_checkpoint_bytes"]:
        raise ValueError("Installed-wheel validation is incomplete")
    installation = result["installation"]
    if installation["version"] != __version__ or pytest_count((path / "pytest.log").read_text()) != count:
        raise ValueError("The installed wheel version/test count differs from source")
    commands = {entry["name"] for entry in result["commands"] if entry["exit_code"] == 0}
    if not {"pytest", "self_check", "referee", "sensitivity", "balance_constraints", "training", "resume"} <= commands:
        raise ValueError("An installed-wheel verification command is missing")
    return installation


def environment_statement(installation: dict, manifest: dict, count: int) -> str:
    if (
        manifest["package_version"] != installation["version"]
        or manifest["source_sha256"] != installation["source_sha256"]
    ):
        raise ValueError("The analytic table belongs to a different release/source")
    if manifest["checks_passed"] != manifest["checks_total"]:
        raise ValueError("The analytic demonstration has failed checks")
    return (
        f"The analytic table was regenerated by the installed {installation['version']} wheel in the "
        f"Python {installation['python']} CPU environment with PyTorch {installation['torch']}, "
        f"NumPy {installation['numpy']}, pandas {installation['pandas']}, and h5py {installation['h5py']}. "
        f"All {count} tests and all {manifest['checks_passed']} analytic checks passed. "
        f"The demonstration used {manifest['torch_threads']} PyTorch thread; its measured audit portion took "
        f"{manifest['elapsed_seconds']:.3f} seconds, excluding imports and installation. "
        "This installation-scale timing is separate from the cost study. The source hash and full environment "
        "are retained in the generated manifest.\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper", type=Path, default=Path("PAPER"))
    parser.add_argument("--validation-current", type=Path)
    parser.add_argument("--validation-minimum", type=Path)
    parser.add_argument("--source-test-log", type=Path)
    parser.add_argument("--locations-document", choices=["main", "main_marked"], default="main")
    args = parser.parse_args()
    paper = args.paper
    generated = paper / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    (generated / "package_version.tex").write_text(
        r"\newcommand{\PackageVersion}{"
        + __version__
        + "}\n"
        + r"\newcommand{\SoftwareReleaseURL}{https://github.com/lennonshikhman/diagnostics_for_physics/releases/tag/v"
        + __version__
        + "}\n"
    )
    paired = json.loads((paper / "revision_evidence/controlled/paired_results.json").read_text())
    adv = next(row for row in paired if row["problem"] == "advection1d")
    ratio = adv["semigroup_reduction"]
    ceiling = max(adv["baseline_l2"], adv["composition_l2"])
    sentence = (
        f"An accuracy-matched advection comparison has state errors below {(int(ceiling * 10) + 1) / 10:.1f}\\% "
        f"with a semigroup-error ratio of {ratio[0]:.2f} (95\\% interval {ratio[1]:.2f}--{ratio[2]:.2f}); "
        "unsuccessful matching cases are retained. "
    )
    contrasts_path = paper / "revision_evidence/rollout/rollout_contrasts.json"
    if contrasts_path.exists():
        contrast = next(row for row in json.loads(contrasts_path.read_text()) if row["problem"] == "advection1d")
        long_ratio = contrast["ratios_supervised_over_composition"]["full_4T"]
        if long_ratio["status"] == "available" and long_ratio["high"] < 1:
            sentence += "Supplementary rollouts retain a counterexample to interpreting smaller semigroup error as better forecast accuracy. "
    (generated / "controlled_abstract.tex").write_text(sentence + r"\ignorespaces" + "\n")
    locations_file = paper / (args.locations_document + ".aux")
    if locations_file.exists():
        labels = compiled_locations(locations_file.read_text())
        lines = [r"\newcommand{\manuloc}[1]{\csname reviewlocation:#1\endcsname}"]
        lines += [
            r"\expandafter\def\csname reviewlocation:" + key + r"\endcsname{" + value + "}"
            for key, value in labels.items()
        ]
        (generated / "review_locations.tex").write_text("\n".join(lines) + "\n")
        changes = [
            (
                "R2.3: composed-state error, both rollout partitions and descriptive correlations",
                ["sec:rollout", "tab:rollout", "tab:rollout_half"],
            ),
            ("All-seed pooling and unsuccessful accuracy-matching attempts", ["sec:matched", "tab:matched"]),
            (
                "Previously computed external amplitude scaling added to tables",
                ["tab:applicability", "tab:external", "tab:external_all"],
            ),
            ("CNS energy components and nonidentical smoothed predictions", ["sec:external_results"]),
            (
                "Genuine octant mass-flux balances, with reference baselines",
                ["sec:balance", "sec:external_results", "tab:external_subvolumes"],
            ),
            ("Explicit smoothing boundary policy", ["sec:smoothing"]),
            ("APEBench complementary-role wording", ["sec:framework", "tab:frameworks"]),
            ("Landscape appendix table layout and additional results", ["app:extended"]),
            ("CSNO, One Operator and consistent author initials", ["sec:related_work"]),
            (
                "Version, installed-wheel verification, Program Summary and unnumbered Code availability",
                ["sec:software_metadata", "sec:cost"],
            ),
            (
                "Reviewer-reference mappings and revised point-by-point response",
                ["sec:learned", "sec:external_results", "sec:generator", "sec:balance"],
            ),
        ]
        change_rows = [
            {"change": change, "locations": [labels[label] for label in keys if label in labels]}
            for change, keys in changes
        ]
        destination = paper / "revision_evidence/postreview_changes.json"
        destination.write_text(json.dumps(change_rows, indent=2) + "\n")
        text = ["# Additional revision changes", "", "Generated from the compiled manuscript labels.", ""]
        text += ["- " + row["change"] + ": " + "; ".join(row["locations"]).replace("~", " ") for row in change_rows]
        (paper / "postreview_changes.md").write_text("\n".join(text) + "\n")
    if args.validation_current or args.validation_minimum or args.source_test_log:
        if not all([args.validation_current, args.validation_minimum, args.source_test_log]):
            raise ValueError("Both wheel environments and source-test log are required together")
        count = pytest_count(args.source_test_log.read_text())
        installations = []
        for path in [args.validation_minimum, args.validation_current]:
            installations.append(validated_installation(path, count))
        minimum, current = installations

        def runtime(d):
            return f"PyTorch {d['torch']}, NumPy {d['numpy']}, pandas {d['pandas']}, h5py {d['h5py']}"

        text = (
            f"All {count} tests passed against the source and against the installed version {__version__} wheel "
            f"outside the checkout in both dependency environments. The minimum CPU environment uses {runtime(minimum)}; "
            f"the current environment uses {runtime(current)}, with Python {current['python']}. "
            "Both installations passed the analytic self-check, 16 referee checks, nine sensitivity checks, "
            "public examples, the manufactured balance/constraint script, and a four-model CPU training/resume check. "
            "Resume preserved all completed checkpoint bytes. These are tested environments, not a claim of "
            "compatibility with every later dependency or platform.\n"
        )
        (generated / "release_validation.tex").write_text(text.replace("_", r"\_"))
        referee = args.validation_minimum / "referee"
        manifest = json.loads((referee / "manifest.json").read_text())
        (generated / "environment.tex").write_text(environment_statement(minimum, manifest, count))
        (generated / "diagnostics.tex").write_bytes((referee / "diagnostics.tex").read_bytes())
        (paper / "revision_evidence/release_summary.json").write_text(
            json.dumps(
                dict(
                    version=__version__,
                    tests=count,
                    environments=installations,
                    source_test_log=str(args.source_test_log),
                ),
                indent=2,
            )
            + "\n"
        )


if __name__ == "__main__":
    main()
